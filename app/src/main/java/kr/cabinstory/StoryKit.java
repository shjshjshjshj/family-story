package kr.cabinstory;

import org.json.*;
import java.util.Arrays;

/**
 * One specification for everything a place needs in the kids guide, whether it is bundled in places.json or
 * generated for a new place: the picture-book pages, the quizzes for the drive, the look-out hint, the recall
 * line, the arrival mission and the facts for the general guide.
 *
 * The model only fills in fields. The wording that must stay identical across places (how a quiz is read out,
 * how the answer is announced) is assembled here, and everything the model returns is checked before use.
 */
final class StoryKit {
    private StoryKit() {}

    /** Raised when the specification changes so places generated by an older one are made again. */
    static final int VERSION = 2;
    static final int PAGES = 8, MIN_PAGES = 5, QUIZZES = 3, FACTS = 3;
    static final String[] ACTIVITIES = {"wave", "point", "walk", "think", "read", "cheer", "stargaze", "photo", "eat", "surprise", "sleep", "listen"};

    /** The writing guideline sent to the model. */
    static String prompt(String name, String overview) {
        String source = overview == null ? "" : overview.length() > 1500 ? overview.substring(0, 1500) : overview;
        return String.join("\n",
            "너는 가족 자동차 여행 앱의 어린이 안내 원고를 쓰는 작가다. 아래 [소개]만 근거로 [장소]의 원고를 쓴다.",
            "",
            "[독자] 5~7세 어린이. 차 안에서 소리로 듣고, 정차했을 때 그림책 화면으로 본다.",
            "[길잡이] 안내하는 동물 캐릭터의 이름은 반드시 {g} 라고만 쓴다. 다른 이름이나 동물 종류를 정하지 않는다.",
            "",
            "[사실 규칙]",
            "- [소개]에 없는 연도, 숫자, 인물, 전설, 시설을 만들지 않는다. 확실하지 않으면 쓰지 않는다.",
            "- 운영 시간, 요금, 예약 같은 바뀌는 정보는 쓰지 않는다.",
            "",
            "[말투]",
            "- 친구에게 말하듯 다정한 반말. 한 문장은 짧게, 소리 내어 읽기 쉽게.",
            "- 숫자는 한글로 풀어 쓴다(예: 삼백 년). 괄호, 영어, 기호, 이모지는 쓰지 않는다.",
            "- 무섭거나 슬픈 표현, 죽음을 자세히 묘사하는 표현은 쓰지 않는다.",
            "",
            "[pages] 그림책 " + PAGES + "쪽. 각 쪽은 제목 12자 이내, 본문 2~4문장.",
            "- 1쪽: {g}가 인사하고 이곳이 어떤 곳인지 한마디로 소개한다.",
            "- 2~6쪽: [소개]에서 아이가 신기해할 내용을 한 쪽에 하나씩. 크기는 아이가 아는 것에 빗대어 말한다.",
            "- 7쪽: 이곳에서 지킬 약속. 보호자와 함께 다니기, 올라가거나 만지지 않고 눈으로 보기.",
            "- 8쪽: 도착해서 또는 집에 돌아가서 해 볼 작은 활동으로 마무리한다.",
            "- 모든 쪽에서 {g}가 직접 무언가를 하거나 느낀다. activity는 본문 속 {g}의 행동과 맞는 것을 고른다: " + String.join(", ", ACTIVITIES),
            "",
            "[quizzes] 가는 길에 낼 퀴즈 " + QUIZZES + "개. [소개]에 나온 사실로만 낸다.",
            "- question은 물음 한 문장. option1과 option2는 짧은 보기. 틀린 보기는 엉뚱하지만 무섭지 않게.",
            "- answer는 맞는 보기 번호 1 또는 2. 정답 번호가 한쪽으로 몰리지 않게 한다.",
            "- explain은 정답을 한 문장으로 다시 말해 준다. '정답은'이라는 말은 넣지 않는다.",
            "",
            "[lookout] 도착 직전에 창밖에서 찾아볼 것 한 문장. '창밖에 ~ 보이는지 찾아봐.' 꼴.",
            "[recall] 이곳을 떠나 다음 장소로 갈 때 떠올려 줄 한 문장. '~했지?' 꼴.",
            "[mission] 도착해서 눈으로 찾아볼 것을 묻는 한 문장. '~ 찾아볼까?' 또는 '~ 세어 볼까?' 꼴. 만지거나 올라가야 하는 일은 안 된다.",
            "",
            "[장소] " + name,
            "[소개] " + source);
    }

    /** The response shape requested from the model (Gemini responseSchema). */
    static JSONObject schema() throws JSONException {
        JSONObject page = object(new String[]{"title", "text", "activity"}, new JSONObject()
            .put("title", string()).put("text", string()).put("activity", string().put("enum", new JSONArray(Arrays.asList(ACTIVITIES)))));
        JSONObject quiz = object(new String[]{"question", "option1", "option2", "answer", "explain"}, new JSONObject()
            .put("question", string()).put("option1", string()).put("option2", string())
            .put("answer", new JSONObject().put("type", "INTEGER")).put("explain", string()));
        return object(new String[]{"pages", "quizzes", "lookout", "recall", "mission"}, new JSONObject()
            .put("pages", array(page)).put("quizzes", array(quiz))
            .put("lookout", string()).put("recall", string()).put("mission", string()));
    }
    private static JSONObject string() throws JSONException { return new JSONObject().put("type", "STRING"); }
    private static JSONObject array(JSONObject items) throws JSONException { return new JSONObject().put("type", "ARRAY").put("items", items); }
    private static JSONObject object(String[] required, JSONObject properties) throws JSONException {
        return new JSONObject().put("type", "OBJECT").put("properties", properties).put("required", new JSONArray(Arrays.asList(required)));
    }

    /**
     * Checks the model's answer and turns it into the stored form. Throws when too little of it is usable,
     * so the caller can fall back instead of showing a broken story.
     */
    static JSONObject parse(String raw, JSONArray adult) throws JSONException {
        JSONObject in = new JSONObject(raw);
        JSONArray pagesIn = in.optJSONArray("pages"), pages = new JSONArray();
        for (int i = 0; pagesIn != null && i < pagesIn.length() && pages.length() < PAGES; i++) {
            JSONObject p = pagesIn.optJSONObject(i);
            if (p == null) continue;
            String title = clean(p.optString("title")), text = clean(p.optString("text")), activity = p.optString("activity").trim();
            if (title.isEmpty() || title.length() > 24 || text.length() < 20 || text.length() > 320) continue;
            if (!Arrays.asList(ACTIVITIES).contains(activity)) activity = ContentService.activityFor(text);
            pages.put(new JSONObject().put("title", title).put("text", text).put("activity", activity));
        }
        if (pages.length() < MIN_PAGES) throw new JSONException("pages " + pages.length());

        JSONArray quizzesIn = in.optJSONArray("quizzes"), quizzes = new JSONArray();
        for (int i = 0; quizzesIn != null && i < quizzesIn.length() && quizzes.length() < QUIZZES; i++) {
            JSONObject q = quizzesIn.optJSONObject(i);
            if (q == null) continue;
            String question = clean(q.optString("question")), one = option(q.optString("option1")), two = option(q.optString("option2"));
            String explain = clean(q.optString("explain")).replaceFirst("^정답은\\s*", "");
            int answer = q.optInt("answer");
            if (question.length() < 6 || question.length() > 90 || one.isEmpty() || two.isEmpty() || one.equals(two)
                || one.length() > 40 || two.length() > 40 || (answer != 1 && answer != 2) || explain.isEmpty() || explain.length() > 90) continue;
            // The spoken form is fixed here so every place sounds the same.
            quizzes.put(new JSONObject()
                .put("q", question + " 일 번, " + one + ". 이 번, " + two + ".")
                .put("a", "정답은 " + (answer == 1 ? "일" : "이") + " 번! " + explain));
        }

        JSONObject journey = new JSONObject().put("kidsQuizzes", quizzes).put("facts", facts(adult));
        String lookout = line(in.optString("lookout")), recall = line(in.optString("recall")), mission = line(in.optString("mission"));
        if (!lookout.isEmpty()) journey.put("kidsLookout", lookout);
        if (!recall.isEmpty()) journey.put("kidsRecall", recall);
        JSONObject out = new JSONObject().put("kit", VERSION).put("kids", pages).put("journey", journey);
        if (!mission.isEmpty() && mission.endsWith("?")) out.put("mission", new JSONObject().put("question", mission).put("activity", "point"));
        return out;
    }

    /** Without the model: a short story from the overview, and the same journey fields as far as they can be filled. */
    static JSONObject fallback(String name, JSONArray adult) throws JSONException {
        String first = adult == null ? "" : adult.optString(0, "");
        JSONArray pages = new JSONArray()
            .put(new JSONObject().put("activity", "wave").put("title", "{g}와 함께 도착!").put("text", "안녕, 나는 이야기 길잡이 {g}야! 여기는 " + name + Journey.josa(name, "이라는", "라는") + " 곳이야. 어떤 곳인지 같이 살펴볼까?"))
            .put(new JSONObject().put("activity", "point").put("title", "{g}가 찾은 이야기").put("text", "{g}가 저쪽을 가리켰어. " + (first.length() > 120 ? first.substring(0, 120) + "…" : first)))
            .put(new JSONObject().put("activity", "photo").put("title", "우리만의 한 장면").put("text", "{g}가 찰칵, 사진을 찍었어. 보호자와 함께 가장 마음에 드는 풍경을 하나 골라 보자. 정해진 길로만 다니는 거야."));
        return new JSONObject().put("kit", 0).put("kids", pages)
            .put("journey", new JSONObject().put("kidsQuizzes", new JSONArray()).put("facts", facts(adult)))
            .put("mission", new JSONObject().put("question", name + "에서 가장 마음에 드는 것을 하나 찾아볼까?").put("activity", "point"));
    }

    /** Facts for the general guide come straight from the official overview, never from the model. */
    static JSONArray facts(JSONArray adult) {
        JSONArray out = new JSONArray();
        for (int i = 0; adult != null && i < adult.length() && out.length() < FACTS; i++) {
            String paragraph = adult.optString(i, "").trim();
            int end = paragraph.indexOf("다. ");
            String sentence = end > 0 ? paragraph.substring(0, end + 2) : paragraph;
            if (sentence.length() >= 15 && sentence.length() <= 160) out.put(sentence);
        }
        return out;
    }

    private static String clean(String value) {
        return value == null ? "" : value.replaceAll("[*_#`]", "").replaceAll("\\s+", " ").trim();
    }
    private static String option(String value) { return clean(value).replaceAll("[.!?]+$", ""); }
    private static String line(String value) {
        String text = clean(value);
        return text.length() < 8 || text.length() > 90 ? "" : text;
    }
}
